"""Build the user manual: reference tables, screenshots and the PDF.

    python tools/make_manual.py              # regenerate docs/manual/generated/*.tex
    python tools/make_manual.py --figures    # ... and the screenshots in docs/manual/figures/
    python tools/make_manual.py --pdf        # ... and compile docs/manual/PowerLab_User_Manual.pdf
    python tools/make_manual.py --all        # all three

The reference tables (every field of every component, every option of every
study) are written from ``FIELDS`` and ``option_fields``, so the manual cannot
drift from the code; ``tests/test_manual.py`` fails when they are stale. The
screenshots are taken with the native Qt platform on a window that is never
shown on screen, with the window settings redirected to a temporary file.
"""

from __future__ import annotations

import argparse
import dataclasses
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from psa.core.components import COMPONENT_CLASSES, FieldSpec  # noqa: E402
from psa.core.export import latex_escape  # noqa: E402
from psa.core.study import STUDY_REGISTRY  # noqa: E402

MANUAL = ROOT / "docs" / "manual"
GENERATED = MANUAL / "generated"
FIGURES = MANUAL / "figures"
PDF_NAME = "PowerLab_User_Manual.pdf"

KIND_TEXT = {"float": "number", "int": "integer", "complex": "complex", "str": "text",
             "bool": "check box", "bus": "bus", "choice": "choice", "element": "element",
             "elements": "elements"}


# --------------------------------------------------------------------------- #
# Reference tables
# --------------------------------------------------------------------------- #


def _code(text: str) -> str:
    """Typewriter text that may break after an underscore, for narrow columns."""
    return r"\code{" + latex_escape(text).replace(r"\_", r"\_\allowbreak{}") + "}"


def _default_text(value) -> str:
    if value is None:
        return "empty"
    if isinstance(value, bool):
        return "on" if value else "off"
    if isinstance(value, complex):
        if value == 0:
            return "0"
        return latex_escape(f"{value.real:g}{value.imag:+g}j")
    if isinstance(value, float):
        return latex_escape(f"{value:g}")
    if value == "":
        return "--"
    return _code(str(value))


def _shown_when(spec: FieldSpec, labels: dict[str, str]) -> str:
    if not spec.visible_if:
        return ""
    field, values = spec.visible_if
    return (r"Shown when \gui{" + latex_escape(labels.get(field, field)) + "} is "
            + " or ".join(_code(v) for v in values) + ".")


def _description(spec: FieldSpec, labels: dict[str, str]) -> str:
    parts = []
    if spec.tooltip:
        text = latex_escape(spec.tooltip.strip())
        parts.append(text if text.endswith(".") else text + ".")
    elif spec.kind == "bus" and type(spec) is FieldSpec:
        parts.append("The bus this terminal is connected to: wire it on the canvas, "
                     "or pick the bus here.")
    elif spec.kind == "bus":
        parts.append("Any bus of the network.")
    if spec.kind == "choice" and spec.choices:
        parts.append("One of " + ", ".join(_code(c) for c in spec.choices) + ".")
    if spec.minimum is not None and spec.maximum is not None:
        parts.append(latex_escape(f"From {spec.minimum:g} to {spec.maximum:g}."))
    elif spec.minimum is not None:
        parts.append(latex_escape(f"At least {spec.minimum:g}."))
    shown = _shown_when(spec, labels)
    if shown:
        parts.append(shown)
    if spec.kind in ("float", "int", "complex") and not spec.parametric:
        parts.append("Numbers only (no expressions).")
    return " ".join(parts)


def fields_table(cls) -> str:
    """Every field of a component class, grouped as the property editor groups them."""
    defaults = {f.name: f.default for f in dataclasses.fields(cls)}
    labels = {s.name: s.label for s in cls.FIELDS}
    rows, group = [], None
    for spec in cls.FIELDS:
        g = spec.group if spec.group != "General" else (
            "General" if spec.name in ("name", "in_service") or spec.kind == "bus"
            else "Parameters")
        if g != group:
            rows.append(r"\fieldgroup{" + latex_escape(g) + "}")
            group = g
        unit = latex_escape(spec.unit) if spec.unit else ""
        rows.append(
            r"\gui{" + latex_escape(spec.label) + r"}\newline" + _code(spec.name)
            + " & " + unit
            + " & " + _default_text(defaults.get(spec.name))
            + " & " + _description(spec, labels) + r" \\")
    return ("% Generated by tools/make_manual.py from "
            f"psa.core.components.{cls.__name__}.FIELDS. Do not edit.\n"
            r"\begin{fieldtable}" + "\n" + "\n".join(rows) + "\n" + r"\end{fieldtable}" + "\n")


def options_table(study) -> str:
    if not study.option_fields:
        return ("% Generated by tools/make_manual.py. Do not edit.\n"
                r"\noindent This study has no options." + "\n")
    labels = {s.name: s.label for s in study.option_fields}
    rows = []
    for spec in study.option_fields:
        kind = KIND_TEXT.get(spec.kind, spec.kind)
        if spec.kind == "element" and getattr(spec, "element_types", ()):
            kind = "a " + " or ".join(spec.element_types)
        unit = f" [{spec.unit}]" if spec.unit else ""
        rows.append(
            r"\gui{" + latex_escape(spec.label + unit) + r"}\newline" + _code(spec.name)
            + " & " + latex_escape(kind)
            + " & " + _description(spec, labels) + r" \\")
    return (f"% Generated by tools/make_manual.py from the options of study "
            f"'{study.key}'. Do not edit.\n"
            r"\begin{optiontable}" + "\n" + "\n".join(rows) + "\n" + r"\end{optiontable}" + "\n")


def generated_tables() -> dict[str, str]:
    """``{file name: LaTeX}`` for every generated reference table."""
    out = {f"fields-{cls.TYPE}.tex": fields_table(cls) for cls in COMPONENT_CLASSES}
    out.update({f"options-{key}.tex": options_table(study)
                for key, study in STUDY_REGISTRY.items()})
    return out


def write_tables() -> None:
    GENERATED.mkdir(parents=True, exist_ok=True)
    for name, text in generated_tables().items():
        (GENERATED / name).write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {len(generated_tables())} tables to {GENERATED.relative_to(ROOT)}")


