def write_pdf() -> None:
    cmd = ["latexmk", "-pdf", "-outdir=build", "-interaction=nonstopmode", "-halt-on-error",
           "manual.tex"]
    result = subprocess.run(cmd, cwd=MANUAL, capture_output=True, text=True)
    if result.returncode != 0:
        print(result.stdout[-4000:])
        raise SystemExit(f"latexmk failed; see {MANUAL / 'build' / 'manual.log'}")
    shutil.copyfile(MANUAL / "build" / "manual.pdf", MANUAL / PDF_NAME)
    print(f"wrote {(MANUAL / PDF_NAME).relative_to(ROOT)}")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--figures", action="store_true", help="also take the screenshots")
    ap.add_argument("--pdf", action="store_true", help="also compile the PDF")
    ap.add_argument("--all", action="store_true", help="tables, screenshots and PDF")
    args = ap.parse_args(argv)
    write_tables()
    if args.figures or args.all:
        write_figures()
    if args.pdf or args.all:
        write_pdf()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
