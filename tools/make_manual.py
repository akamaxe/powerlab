def write_figures() -> None:
    """Every screenshot of the manual, from the example projects."""
    import psa.gui  # noqa: F401 - the ICU preload must come before PySide6
    from PySide6.QtCore import QPoint, QSettings, Qt
    from PySide6.QtGui import QPainter, QPixmap

    settings_dir = tempfile.mkdtemp(prefix="powerlab-manual-")
    QSettings.setDefaultFormat(QSettings.Format.IniFormat)
    QSettings.setPath(QSettings.Format.IniFormat, QSettings.Scope.UserScope, settings_dir)

    from psa.core.study import STUDY_REGISTRY as REG
    from psa.gui.app import create_app
    from psa.gui.datamanager import DataManagerPanel
    from psa.gui.dialogs import BaseSettingsDialog, CaseDialog
    from psa.gui.document import NetworkDocument
    from psa.gui.export import export_diagram
    from psa.gui.mainwindow import MainWindow
    from psa.gui.panels import PropertyEditor, ResultsPanel, symbol_icon
    from psa.gui.registry import ELEMENT_UI

    app = create_app([sys.argv[0]])
    FIGURES.mkdir(parents=True, exist_ok=True)
    hidden = Qt.WidgetAttribute.WA_DontShowOnScreen

    def settle():
        for _ in range(3):
            app.processEvents()

    def save(pixmap, name):
        path = FIGURES / name
        pixmap.save(str(path))
        print("  ", path.relative_to(ROOT))

    def window(example: str, size=(1600, 1000)) -> MainWindow:
        win = MainWindow(NetworkDocument.open(ROOT / "examples" / example, as_copy=True))
        win.setAttribute(hidden, True)
        win.resize(*size)
        win.show()
        settle()
        return win

    def close(win) -> None:
        win.document.undo.setClean()
        win.close()

    def properties(doc, obj_id: str, name: str, height: int = 900) -> None:
        editor = PropertyEditor(doc)
        editor.setAttribute(hidden, True)
        editor.bind(obj_id)
        editor.resize(430, height)
        editor.show()
        settle()
        save(editor.grab(), name)
        editor.close()

    # The whole window, with numbered callouts placed from the real geometry
    win = window("lf_220kv.psn")
    win.run_all_studies()
    win.results.setCurrentIndex(0)
    win.focus_element("G7")
    win.view.zoom_fit()
    settle()
    save(win.grab(), "window-overview.png")
    w, h = win.width(), win.height()

    def spot(widget, dx=0.5, dy=0.0, oy=14):
        top_left = widget.mapTo(win, QPoint(0, 0))
        x = top_left.x() + dx * widget.width()
        y = top_left.y() + dy * widget.height() + oy
        return x / w, 1.0 - y / h

    regions = [
        ("menubar", win.menuBar(), 0.33, 0.0, 10),
        ("toolbar", win.toolbar, 0.62, 0.0, 14),
        ("library", win.dock_library, 0.62, 0.0, 12),
        ("variables", win.dock_variables, 0.62, 0.0, 12),
        ("canvas", win.view, 0.04, 0.0, 22),
        ("properties", win.dock_properties, 0.55, 0.0, 12),
        ("cases", win.dock_cases, 0.55, 0.0, 12),
        ("results", win.dock_results, 0.2, 0.0, 12),
        ("status", win.statusBar(), 0.5, 0.0, 10),
    ]
    lines = ["% Generated by tools/make_manual.py: callout positions on window-overview.png."]
    for n, (key, widget, dx, dy, oy) in enumerate(regions, start=1):
        fx, fy = spot(widget, dx, dy, oy)
        lines.append(rf"\windowcallout{{{fx:.4f}}}{{{fy:.4f}}}{{{n}}}% {key}")
    (GENERATED / "window-callouts.tex").write_text("\n".join(lines) + "\n", encoding="utf-8",
                                                   newline="\n")

    export_diagram(win.scene, FIGURES / "diagram-lf.png")
    print("   docs/manual/figures/diagram-lf.png")

    # Panels of that window
    for dock, name in ((win.dock_cases, "panel-cases.png"),
                       (win.dock_library, "panel-library.png")):
        save(dock.grab(), name)
    properties(win.document, "G7", "properties-generator.png", 560)
    win.set_colour_mode("voltage")
    win.view.zoom_fit()
    settle()
    save(win.view.grab(), "colour-voltage.png")

    # Context menus and the Calculate menu
    item = win.scene.item_for("b2")
    menu = win.scene.build_context_menu(item)
    menu.setAttribute(hidden, True)
    menu.popup(win.mapToGlobal(win.rect().center()))
    settle()
    save(menu.grab(), "menu-bus.png")
    menu.close()
    for action in win.menuBar().actions():
        if action.text().replace("&", "") == "Calculate":
            calc = action.menu()
            calc.setAttribute(hidden, True)
            calc.popup(win.mapToGlobal(win.rect().center()))
            settle()
            save(calc.grab(), "menu-calculate.png")
            calc.close()

    # Case dialog, both tabs
    dialog = CaseDialog(win.document, REG["loadflow"], win.document.case("LFd"), win)
    dialog.setAttribute(hidden, True)
    dialog.show()
    settle()
    save(dialog.grab(), "dialog-case-options.png")
    dialog.tabs.setCurrentIndex(1)
    settle()
    save(dialog.grab(), "dialog-case-variant.png")
    dialog.close()

    # Results, standalone and large
    panel = ResultsPanel(win.document)
    panel.setAttribute(hidden, True)
    panel.show_results(win.results.all_results())
    panel.resize(1250, 1500)
    panel.show()
    settle()
    save(panel.grab(), "results-loadflow.png")
    panel.close()

    # Data manager, standalone
    dm = DataManagerPanel(win.document)
    dm.setAttribute(hidden, True)
    dm.show_type("line")
    dm.resize(1300, 420)
    dm.show()
    settle()
    save(dm.grab(), "data-manager.png")
    dm.close()
    close(win)

    # S1: variables, a parametric field, the diagram
    win = window("s1_a80.psn")
    save(win.dock_variables.grab(), "panel-variables.png")
    properties(win.document, "LDe", "properties-load.png", 700)
    win.run_all_studies()
    win.results.setCurrentIndex(3)
    settle()
    export_diagram(win.scene, FIGURES / "diagram-s1.png")
    print("   docs/manual/figures/diagram-s1.png")
    close(win)

    # S2 + industry: grid properties, base settings, variant dialog, colouring
    win = window("grid_industry.psn")
    properties(win.document, "GRID", "properties-grid.png", 860)
    dialog = BaseSettingsDialog(win.document, win)
    dialog.setAttribute(hidden, True)
    dialog.show()
    settle()
    save(dialog.grab(), "dialog-bases.png")
    dialog.close()
    dialog = CaseDialog(win.document, REG["ybus"], win.document.case("S2a"), win)
    dialog.setAttribute(hidden, True)
    dialog.tabs.setCurrentIndex(1)
    dialog.show()
    settle()
    save(dialog.grab(), "dialog-case-exclude.png")
    dialog.close()
    win.run_all_studies()
    titles = [win.results.tabText(i) for i in range(win.results.count())]
    win.results.setCurrentIndex(next(i for i, t in enumerate(titles) if t.startswith("S2d")))
    settle()
    export_diagram(win.scene, FIGURES / "diagram-s2d.png")
    print("   docs/manual/figures/diagram-s2d.png")
    win.results.setCurrentIndex(next(i for i, t in enumerate(titles) if t.startswith("S3c")))
    settle()
    export_diagram(win.scene, FIGURES / "diagram-s3c.png")
    print("   docs/manual/figures/diagram-s3c.png")
    win.set_colour_mode("level")
    win.act_overlay.setChecked(False)
    win._toggle_overlay()
    win.view.zoom_fit()
    settle()
    save(win.view.grab(), "colour-level.png")
    close(win)

    # Palette icons, one per component type, cropped to the symbol
    for entry in ELEMENT_UI.values():
        pix = QPixmap(192, 192)
        pix.fill(Qt.GlobalColor.transparent)
        painter = QPainter(pix)
        symbol_icon(entry.type).paint(painter, pix.rect())
        painter.end()
        image = pix.toImage()
        xs, ys = [], []
        for y in range(image.height()):
            for x in range(image.width()):
                if image.pixelColor(x, y).alpha() > 0:
                    xs.append(x)
                    ys.append(y)
        if xs:
            side = max(max(xs) - min(xs), max(ys) - min(ys)) + 8
            cx, cy = (min(xs) + max(xs)) // 2, (min(ys) + max(ys)) // 2
            image = image.copy(cx - side // 2, cy - side // 2, side, side)
        save(QPixmap.fromImage(image), f"icon-{entry.type}.png")
    shutil.rmtree(settings_dir, ignore_errors=True)


